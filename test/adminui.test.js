'use strict';
const assert = require('assert');
const ui = require('../adminui');
assert.ok(ui.GROUPS.some((g) => g.id === 'kontakt'));
assert.ok(ui.searchIndex().some((t) => t.href === '/admin/kontakt' && /email|telegram/i.test(t.q)));
const html = ui.dashboard({ slug: 'tv', msg: '' });
assert.ok(html.includes('Kontaktné údaje'));
assert.ok(html.includes('/admin/kontakt'));
assert.ok(!/tokigo/i.test(html));
const sh = ui.shell({ title: 'Admin', body: '<h1>x</h1>', cssV: '1' });
assert.ok(sh.includes('adside') && sh.includes('adSearch'));
const login = ui.shell({ title: 'Prihlásenie', body: '<form>', cls: 'adm login', cssV: '1' });
assert.ok(!login.includes('adside'));
const acc = require('fs').readFileSync(require('path').join(__dirname, '../accounts.js'), 'utf8');
assert.ok(!/API kľúč – len XUI|id="pk"|name="key"/.test(acc), 'predplatné-server must not have an API key field');
assert.ok(acc.includes('Admin / reseller meno') && acc.includes('Admin heslo'));
assert.ok(acc.includes('posledný známy dátum'));
assert.ok(!/zadajte API kľúč XUI/i.test(acc));
assert.ok(acc.includes('http://ip-alebo-domena:port'));
assert.ok(acc.includes('HTTP aj HTTPS sú plne podporované'));
assert.ok(!/Adresa bola prepnuta z http:\/\/ na https/.test(acc));
assert.ok(!/httpsTwin/.test(acc));
console.log('ok adminui');
